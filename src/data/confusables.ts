/** Код страны → все коды, с которыми она входит в общую группу. */
export const CONFUSABLE_MAP: ReadonlyMap<string, string[]> = (() => {
  const map = new Map<string, Set<string>>();
  for (const group of CONFUSABLE_GROUPS) {
    for (const code of group) {
      const set = map.get(code) ?? new Set<string>();
      for (const other of group) if (other !== code) set.add(other);
      map.set(code, set);
    }
  }
  return new Map([...map].map(([code, set]) => [code, [...set]]));
})();
